def workshop_card_text(w: Workshop, free_places: int) -> str:
    """Карточка мастерской."""
    lines = [
        f"🛠 <b>{w.title}</b>",
        f"Формат: {'специальная' if w.format == 'специальная' else 'базовая'}",
        "",
        w.description,
        "",
        f"📅 Дата: {w.date}",
        f"📍 Место: {w.location}",
    ]
    if w.format == "специальная":
        lines.append(f"🔁 Количество занятий: {w.lessons_count}")
        lines.append(f"🗓 Дни проведения: {w.days}")
    lines.append("")
    lines.append(f" Свободных мест: <b>{free_places}</b>")
    return "\n".join(lines)


